#!/usr/bin/env python3
"""Deterministic authored-only Luau -> bytecode -> decompile -> behavior suite."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
from datetime import datetime, timezone


HERE = Path(__file__).resolve().parent
DEFAULT_ROOT = HERE.parent


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def run(cmd: list[str], *, cwd: Path) -> subprocess.CompletedProcess[bytes]:
    try:
        return subprocess.run(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=20)
    except subprocess.TimeoutExpired as e:
        return subprocess.CompletedProcess(cmd, 124, e.stdout or b"", (e.stderr or b"") + b"\nfixture timed out")


def text(data: bytes) -> str:
    return data.decode("utf-8", errors="replace")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--decompiler", help="path to luaudec.exe to evaluate (legacy local build mode)")
    parser.add_argument("--tools", help="tools.json generated by this skill's setup command")
    parser.add_argument("--root", default=str(DEFAULT_ROOT), help="v032 directory containing build/luau")
    parser.add_argument("--out", default=str(HERE / "results.json"), help="JSON report destination")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    if args.tools:
        tools = json.loads(Path(args.tools).read_text(encoding="utf-8"))
        decompiler = Path(tools["decompiler"]["argv"][0])
        compiler = Path(tools["compiler"]["argv"][0])
        runner = Path(tools["runner"]["argv"][0])
        root = Path(args.tools).resolve().parent
    else:
        if not args.decompiler:
            parser.error("--tools or --decompiler is required")
        decompiler = Path(args.decompiler).resolve()
        compiler = root / "build" / "luau" / "Release" / "luau-compile.exe"
        runner = root / "build" / "luau" / "Release" / "luau.exe"
    for exe in (decompiler, compiler, runner):
        if not exe.is_file():
            parser.error(f"executable not found: {exe}")

    expected = json.loads((HERE / "cases.json").read_text(encoding="utf-8"))
    artifacts = Path(args.out).resolve().with_suffix("").with_name(Path(args.out).stem + "-artifacts")
    artifacts.mkdir(parents=True, exist_ok=True)
    records = []

    for source in sorted((HERE / "cases").glob("*.luau")):
        name = source.stem
        source_text = source.read_text(encoding="utf-8")
        source_hash = sha256(source)
        case_record = {
            "case": name,
            "input": {"path": str(source), "sha256": source_hash, "source": source_text},
            "expected": {"stdout": expected[name], "exit_code": 0},
            "optimization_levels": [],
        }
        for opt in (0, 1, 2):
            opt_dir = artifacts / name / f"O{opt}"
            opt_dir.mkdir(parents=True, exist_ok=True)
            bytecode = opt_dir / f"{name}.luauc"
            recovered = opt_dir / f"{name}.recovered.luau"

            compile_cmd = [str(compiler), "--binary", f"-O{opt}", str(source)]
            compiled = run(compile_cmd, cwd=root)
            bytecode.write_bytes(compiled.stdout)

            decompile_cmd = [str(decompiler), "--standard", "--no-header", str(bytecode)]
            decompiled = run(decompile_cmd, cwd=root)
            recovered.write_bytes(decompiled.stdout)

            syntax_cmd = [str(compiler), "--only-parse", str(recovered)]
            syntax = run(syntax_cmd, cwd=root)

            original_cmd = [str(runner), f"-O{opt}", str(source)]
            original = run(original_cmd, cwd=root)
            recovered_cmd = [str(runner), f"-O{opt}", str(recovered)]
            recovered_run = run(recovered_cmd, cwd=root) if syntax.returncode == 0 else None

            normalized = lambda b: b.replace(b"\r\n", b"\n")
            original_match = normalized(original.stdout) == normalized(expected[name].encode()) and original.returncode == 0
            recovered_match = (
                recovered_run is not None
                and normalized(recovered_run.stdout) == normalized(original.stdout)
                and recovered_run.returncode == original.returncode
            )
            # Static CFG comparison is independent of the observed behavior test.
            sys.path.insert(0, str(HERE.parents[1] / "scripts"))
            from cfg_verify import compare, disassemble
            cfg = {"status": "UNVERIFIED"}
            if syntax.returncode == 0:
                recompiled = run([str(compiler), "--binary", f"-O{opt}", str(recovered)], cwd=root)
                compiled_recovery = opt_dir / "recompiled.bytecode"
                compiled_recovery.write_bytes(recompiled.stdout)
                if recompiled.returncode == 0:
                    cfg = compare(disassemble(decompiler, bytecode, "standard"), disassemble(decompiler, compiled_recovery, "standard"))
            (opt_dir / "cfg-comparison.json").write_text(json.dumps(cfg, indent=2), encoding="utf-8")
            case_record["optimization_levels"].append({
                "level": opt,
                "verification": {"syntax": "SYNTAX_VALID" if syntax.returncode == 0 else "SYNTAX_INVALID",
                                 "cfg": cfg["status"], "behavior": "BEHAVIOR_VERIFIED" if recovered_match and original_match else "BEHAVIOR_FAILED"},
                "commands": {
                    "compile": compile_cmd,
                    "decompile": decompile_cmd,
                    "syntax_check": syntax_cmd,
                    "run_original": original_cmd,
                    "run_recovered": recovered_cmd,
                },
                "compile": {
                    "exit_code": compiled.returncode,
                    "stderr": text(compiled.stderr),
                    "bytecode_path": str(bytecode),
                    "bytecode_sha256": sha256(bytecode),
                },
                "decompile": {
                    "exit_code": decompiled.returncode,
                    "stderr": text(decompiled.stderr),
                    "recovered_path": str(recovered),
                    "recovered_sha256": sha256(recovered),
                },
                "syntax": {
                    "passed": syntax.returncode == 0,
                    "exit_code": syntax.returncode,
                    "stdout": text(syntax.stdout),
                    "stderr": text(syntax.stderr),
                },
                "behavior": {
                    "original": {"exit_code": original.returncode, "stdout": text(original.stdout), "stderr": text(original.stderr)},
                    "recovered": None if recovered_run is None else {
                        "exit_code": recovered_run.returncode,
                        "stdout": text(recovered_run.stdout),
                        "stderr": text(recovered_run.stderr),
                    },
                    "original_matches_expected": original_match,
                    "recovered_matches_original": recovered_match,
                    "passed": original_match and recovered_match,
                },
            })
        records.append(case_record)

    execs = {"decompiler": decompiler, "compiler": compiler, "runner": runner}
    report = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "scope": "authored deterministic Luau fixtures only; no game code or Roblox connection",
        "executables": {key: {"path": str(path), "sha256": sha256(path)} for key, path in execs.items()},
        "optimization_levels": [0, 1, 2],
        "counts": {},
        "cases": records,
    }
    level_records = [level for case in records for level in case["optimization_levels"]]
    report["counts"] = {
        "cases": len(records),
        "compiled": sum(level["compile"]["exit_code"] == 0 for level in level_records),
        "syntax_passed": sum(level["syntax"]["passed"] for level in level_records),
        "behavior_passed": sum(level["behavior"]["passed"] for level in level_records),
        "total_runs": len(level_records),
        "failures": sum(not level["behavior"]["passed"] or not level["syntax"]["passed"] or level["compile"]["exit_code"] != 0 or level["decompile"]["exit_code"] != 0 for level in level_records),
    }
    out = Path(args.out).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps({"report": str(out), **report["counts"]}, indent=2))
    return 0 if report["counts"]["failures"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
